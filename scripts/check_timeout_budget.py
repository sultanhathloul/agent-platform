"""The timeout budget, checked (timeout budget PR, I9, ADR-0261; the PR #12 review, decision 9,
ADR-0269; docs/RESILIENCE.md).

Reads the files that set the platform's bounds — config/turn.yaml, config/models.yaml,
config/docs.yaml, config/mcp.yaml, every capability manifest (and each tool's bound),
infra/litellm/config.yaml, the gateway's application.yml, the agent's Dockerfile,
docker-compose.yml and docker-compose.dev.yml, and the agent modules whose margins nest a bound —
with the loader the agent uses too (services/agent/app/resilience/budget_values.py), and applies
the rules of services/agent/app/resilience/budget.py, the one module that holds them; the settings
page's save applies the same rules (ADR-0277). Exits 1 when a rule fails, a rule the shipped
configuration must produce is missing, or config/deploy-values.yaml no longer matches the files it
copies.

    uv run scripts/check_timeout_budget.py             # make test runs it
    uv run scripts/check_timeout_budget.py --self-test # each rule fails on its own violating value
    uv run scripts/check_timeout_budget.py --write-deploy-values   # regenerate config/deploy-values.yaml"""

import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "services/agent"))

from app.resilience import budget  # noqa: E402  (the rules; standard library only)
from app.resilience import budget_values  # noqa: E402  (the values the rules read; PyYAML only)

DEPLOY_HEADER = """\
# Generated by `uv run scripts/check_timeout_budget.py --write-deploy-values`; never edited by hand.
# The bounds only a redeploy changes, which the agent's container cannot read, copied from the files
# named under `sources` (ADR-0277). The agent reads this file to check a settings save against the
# same rules as `make test`, and the settings page shows these values read-only. `make test` fails
# when this file no longer matches those files: change them, then run the command above.
"""


def _duration_s(text: str) -> float:
    """A Spring Boot duration (`60s`, `500ms`, `2m`) in seconds."""
    match = re.fullmatch(r"(\d+(?:\.\d+)?)(ms|s|m)", str(text).strip())
    if not match:
        raise ValueError(f"not a duration: {text!r}")
    value, unit = float(match[1]), match[2]
    return value / 1000 if unit == "ms" else value * 60 if unit == "m" else value


def _size_mb(text: str) -> float:
    """A Compose memory size (`2g`, `768m`) in MiB."""
    match = re.fullmatch(r"(\d+(?:\.\d+)?)([gm])", str(text).strip().lower())
    if not match:
        raise ValueError(f"not a memory size: {text!r}")
    return float(match[1]) * (1024 if match[2] == "g" else 1)


def _keep_alive(text: str) -> float:
    match = re.search(r'"--timeout-keep-alive",\s*"(\d+)"', text)
    return float(match[1]) if match else 5.0  # uvicorn's own default


def deploy_values(repo: Path = REPO) -> dict:
    """The redeploy-only values, read from the files that set them (config/deploy-values.yaml's
    content)."""
    gateway = yaml.safe_load((repo / "services/gateway/src/main/resources/application.yml").read_text())
    compose = yaml.safe_load((repo / "docker-compose.yml").read_text(encoding="utf-8"))["services"]
    litellm = yaml.safe_load((repo / "infra/litellm/config.yaml").read_text(encoding="utf-8"))["litellm_settings"]
    rag_ref = (repo / "infra/mcp-ref/mcp_ref/rag/server.py").read_text(encoding="utf-8")
    return {
        "gateway": {
            "response_timeout_s": _duration_s(gateway["gateway"]["agent"]["response-timeout"]),
            "keep_alive_s": _duration_s(gateway["gateway"]["agent"]["keep-alive"]),
            "connection_upload_timeout_s": _duration_s(gateway["server"]["tomcat"]["connection-upload-timeout"]),
        },
        "agent_keep_alive_s": _keep_alive((repo / "services/agent/Dockerfile").read_text(encoding="utf-8")),
        "agent_keep_alive_dev_s": _keep_alive((repo / "docker-compose.dev.yml").read_text(encoding="utf-8")),
        "litellm": {
            "request_timeout": float(litellm["request_timeout"]),
            "num_retries": float(litellm.get("num_retries", 0)),
        },
        "mcp_rag_ref_workers": int(budget_values.constant(rag_ref, "WORKERS", "infra/mcp-ref/mcp_ref/rag/server.py")),
        "mem_limits_mb": {name: _size_mb(compose[name]["mem_limit"]) for name in ("ingest", "mcp-rag-ref")},
        "sources": {
            "gateway.response_timeout_s": "services/gateway/src/main/resources/application.yml "
            "gateway.agent.response-timeout",
            "gateway.keep_alive_s": "services/gateway/src/main/resources/application.yml gateway.agent.keep-alive",
            "gateway.connection_upload_timeout_s": "services/gateway/src/main/resources/application.yml "
            "server.tomcat.connection-upload-timeout",
            "agent_keep_alive_s": "services/agent/Dockerfile uvicorn --timeout-keep-alive",
            "agent_keep_alive_dev_s": "docker-compose.dev.yml uvicorn --timeout-keep-alive",
            "litellm.request_timeout": "infra/litellm/config.yaml litellm_settings.request_timeout",
            "litellm.num_retries": "infra/litellm/config.yaml litellm_settings.num_retries",
            "mcp_rag_ref_workers": "infra/mcp-ref/mcp_ref/rag/server.py WORKERS",
            "mem_limits_mb.ingest": "docker-compose.yml services.ingest.mem_limit",
            "mem_limits_mb.mcp-rag-ref": "docker-compose.yml services.mcp-rag-ref.mem_limit",
        },
    }


def render_deploy_values(values: dict) -> str:
    return DEPLOY_HEADER + yaml.safe_dump(values, allow_unicode=True, sort_keys=False, width=110)


def deploy_drift(repo: Path = REPO) -> str | None:
    """None when config/deploy-values.yaml matches the files; otherwise what differs."""
    path = repo / "config" / budget_values.DEPLOY_VALUES
    if not path.is_file():
        return f"{path.relative_to(repo)} is missing"
    if budget_values.load_deploy(repo / "config") != deploy_values(repo):
        return f"{path.relative_to(repo)} differs from the files it is generated from"
    return None


def load(repo: Path = REPO) -> dict:
    """Every value the rules read, by the file it comes from: the shared loader, with the
    redeploy-only values read from their own files."""
    return budget_values.load_values(repo / "config", repo / "services/agent/app", deploy_values(repo))


def report(values: dict) -> int:
    drift = deploy_drift()
    print(f"  {'FAIL' if drift else 'ok  '}  deploy-values — {drift or 'config/deploy-values.yaml matches its files'}")
    found, missing = budget.verify(values)
    failed = [check for check in found if not check.holds]
    for check in found:
        print(f"  {'ok  ' if check.holds else 'FAIL'}  {check.name} — {check.row}: {check.detail}")
    for name in missing:
        print(f"  FAIL  {name}: expected, but the configuration produced no such rule")
    print(f"timeout budget {len(found) - len(failed)} / {len(failed) + len(missing)} / 0")
    return 1 if failed or missing or drift else 0


def self_test(values: dict) -> int:
    found, missing = budget.verify(values)
    if missing or not all(check.holds for check in found):
        print("  FAIL  self-test: the shipped values must pass first")
        return 1
    problems = budget.self_test(values)
    for problem in problems:
        print(f"  FAIL  self-test: {problem}")
    total = len(budget.mutations(values))
    print(f"timeout budget self-test {total - len(problems)} / {len(problems)} / 0")
    return 1 if problems else 0


if __name__ == "__main__":
    if "--write-deploy-values" in sys.argv[1:]:
        (REPO / "config" / budget_values.DEPLOY_VALUES).write_text(
            render_deploy_values(deploy_values()), encoding="utf-8"
        )
        sys.exit(0)
    values = load()
    sys.exit(self_test(values) if "--self-test" in sys.argv[1:] else report(values))
