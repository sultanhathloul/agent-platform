"""The values the timeout budget's rules read (app/resilience/budget.py), built the same way by
scripts/check_timeout_budget.py and by the agent's settings page (ADR-0277): from config/ (turn,
models, docs, mcp, and deploy-values.yaml), the capability manifests and tool modules under the
agent's app/, and the agent modules whose margins nest a bound.

config/deploy-values.yaml holds what only a redeploy changes and the agent's container cannot read
(the gateway's application.yml, the agent's Dockerfile and the dev overlay, docker-compose.yml's
memory limits, LiteLLM's config, the reference RAG server's workers). It is generated by
`uv run scripts/check_timeout_budget.py --write-deploy-values`, and `make test` fails when it no
longer matches the files it was generated from.

PyYAML and the standard library only, so the script can import it."""

import re
from pathlib import Path

import yaml

# The agent modules whose code must use the margins (budget's `*-used` rules).
SOURCES = ("models/gateway.py", "mcp/client.py")
DEPLOY_VALUES = "deploy-values.yaml"


def constant(text: str, name: str, where: str) -> float:
    match = re.search(rf"^{name}\s*=\s*([0-9.]+)", text, re.MULTILINE)
    if not match:
        raise ValueError(f"{where}: no {name}")
    return float(match[1])


def tool_bounds(app_dir: Path) -> dict[str, float]:
    """Each in-process tool's ToolSpec timeout_s, by tool name, read from the capabilities'
    tools.py (the broker bounds a tool by it)."""
    tools: dict[str, float] = {}
    for path in sorted((app_dir / "capabilities").glob("*/tools.py")):
        text = path.read_text(encoding="utf-8")
        for name, bound in re.findall(r'name="([a-z_]+)".*?timeout_s=(\d+(?:\.\d+)?)', text, re.DOTALL):
            tools[name] = float(bound)
    return tools


def load_deploy(config_dir: Path) -> dict:
    return yaml.safe_load((config_dir / DEPLOY_VALUES).read_text(encoding="utf-8"))


def load_values(config_dir: Path, app_dir: Path, deploy: dict | None = None) -> dict:
    """Every value the rules read, by the file it comes from. `deploy` defaults to
    config/deploy-values.yaml."""
    deploy = load_deploy(config_dir) if deploy is None else deploy
    manifests = {
        path.parent.name: yaml.safe_load(path.read_text(encoding="utf-8"))
        for path in sorted((app_dir / "capabilities").glob("*/manifest.yaml"))
    }
    docs = yaml.safe_load((config_dir / "docs.yaml").read_text(encoding="utf-8"))
    client = (app_dir / "mcp/client.py").read_text(encoding="utf-8")
    gateway = (app_dir / "models/gateway.py").read_text(encoding="utf-8")
    return {
        "turn": yaml.safe_load((config_dir / "turn.yaml").read_text(encoding="utf-8")),
        "models": yaml.safe_load((config_dir / "models.yaml").read_text(encoding="utf-8")),
        "docs": docs,
        "mcp": yaml.safe_load((config_dir / "mcp.yaml").read_text(encoding="utf-8")),
        "manifests": manifests,
        "tools": tool_bounds(app_dir),
        "litellm": {"litellm_settings": dict(deploy["litellm"])},
        "gateway": dict(deploy["gateway"]),
        "agent_keep_alive_s": float(deploy["agent_keep_alive_s"]),
        "agent_keep_alive_dev_s": float(deploy["agent_keep_alive_dev_s"]),
        # Sandbox children per document service (ADR-0252): ingest's from config/docs.yaml, the
        # reference RAG server's from its own module.
        "sandbox_workers": {
            "ingest": int(docs["ingest"]["workers"]),
            "mcp-rag-ref": int(deploy["mcp_rag_ref_workers"]),
        },
        "mem_limits_mb": {name: float(mb) for name, mb in deploy["mem_limits_mb"].items()},
        "constants": {
            "sdk_read_margin_s": constant(client, "_SDK_READ_MARGIN_S", "mcp/client.py"),
            "attempt_margin_s": constant(client, "_ATTEMPT_MARGIN_S", "mcp/client.py"),
            "broker_margin_s": constant(
                (app_dir / "mcp/tools.py").read_text(encoding="utf-8"), "_BROKER_MARGIN_S", "mcp/tools.py"
            ),
            "client_margin_s": constant(gateway, "CLIENT_MARGIN_S", "models/gateway.py"),
            "litellm_margin_s": constant(gateway, "LITELLM_MARGIN_S", "models/gateway.py"),
        },
        "sources": {name: (app_dir / name).read_text(encoding="utf-8") for name in SOURCES},
    }
